/**
 * Checks if a string is a protected identifier that must NOT be translated:
 * - Pure numbers, percentages, dates, times
 * - URLs, emails
 * - Batch codes, Order IDs, PHC IDs, Officer IDs
 * - Medicine/Drug names from the NLEM formulary
 */
export function isProtectedUntranslatableToken(text: string): boolean {
  const clean = text.trim();
  if (!clean) return true;
  if (clean === 'MEDRESQ AI' || clean === 'MedResQ AI' || clean === 'Gemini' || clean === 'Firebase') {
    return true;
  }
  // Numeric, currency, date, time, or technical ID patterns
  if (/^[\d\s.,:%+\-–—/()[\]#@•·|°℃]+$/.test(clean)) return true;
  if (/^(?:ORD|PHC|BATCH|LOG|OSN|MDR|BWR|PPL|LNI|CHC|SDH|RMSCL|NLEM|ORS|PCM|AMX|ASV|ARV|ZNC)[-_A-Z0-9]+$/i.test(clean)) {
    return true;
  }
  if (/^https?:\/\//i.test(clean) || /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(clean)) return true;
  // Exact NLEM Medicine Formulary Names
  if (
    /^(?:Paracetamol Tablets|Oral Rehydration Salts|Amoxicillin Capsules|Normal Saline|Ringer Lactate|Zinc Sulfate|Polyvalent Anti-Snake Venom|Anti-Rabies Vaccine|Azithromycin Tablets|Metformin Hydrochloride|Amlodipine Tablets|Omeprazole Capsules|Iron and Folic Acid|Oxytocin Injection|Salbutamol Respirator|Metronidazole Tablets|Ciprofloxacin Hydrochloride|Ibuprofen Tablets|Pantoprazole|Cetirizine|Albendazole|Diclofenac|Ondansetron|Misoprostol|Magnesium Sulfate|Ceftriaxone|Gentamicin)/i.test(
      clean
    ) &&
    clean.length < 68 &&
    !clean.includes('dropped to') &&
    !clean.includes('below')
  ) {
    return true;
  }
  return false;
}

/**
 * Translates any UI string into the selected global language ('en' | 'hi' | 'pa' | 'ta' | 'te' | 'ml').
 * Falls back safely to English if no translation rule matches. Never returns undefined or null.
 */
export function translateUiText(rawText: string, lang: SupportedLanguageCode): string {
  if (!rawText || lang === 'en') return rawText || '';
  const trimmed = rawText.trim();
  if (!trimmed || isProtectedUntranslatableToken(trimmed)) return rawText;

  const targetLang = lang as LangFive;

  // 1. Exact phrase match
  const exact = UI_EXACT_PHRASES[trimmed];
  if (exact && exact[targetLang]) {
    const leading = rawText.match(/^\s*/)?.[0] || '';
    const trailing = rawText.match(/\s*$/)?.[0] || '';
    return `${leading}${exact[targetLang]}${trailing}`;
  }

  // 2. Dynamic pattern matches (e.g. "Order +200", "All (18)", "Pending Review (3)", "85% Uploaded", "Go Online & Sync (3)")
  const orderPlusMatch = trimmed.match(/^Order\s*\+([\d,]+)$/i);
  if (orderPlusMatch) {
    const num = orderPlusMatch[1];
    const map: PhraseTuple = p(
      `ऑर्डर +${num}`,
      `ਆਰਡਰ +${num}`,
      `ஆர்டர் +${num}`,
      `ఆర్డర్ +${num}`,
      `ഓർഡർ +${num}`
    );
    return map[targetLang];
  }

  const filterCountMatch = trimmed.match(
    /^(All|Pending Review|Approved|Rejected|Dispatched|Received|Active|Critical|Warning|Normal|Surplus)\s*\((\d+)\)$/i
  );
  if (filterCountMatch) {
    const labelKey = filterCountMatch[1];
    const count = filterCountMatch[2];
    const translatedLabel =
      UI_EXACT_PHRASES[labelKey]?.[targetLang] ||
      UI_EXACT_PHRASES[labelKey.toUpperCase()]?.[targetLang] ||
      labelKey;
    return `${translatedLabel} (${count})`;
  }

  const goOnlineMatch = trimmed.match(/^Go Online & Sync\s*\((\d+)\)$/i);
  if (goOnlineMatch) {
    const count = goOnlineMatch[1];
    return `${UI_EXACT_PHRASES['Go Online & Sync'][targetLang]} (${count})`;
  }

  const offlineQueueCountMatch = trimmed.match(/^Offline Queue\s*\((\d+)\)$/i);
  if (offlineQueueCountMatch) {
    const count = offlineQueueCountMatch[1];
    const map = p(
      `ऑफ़लाइन कतार (${count})`,
      `ਆਫ਼ਲਾਈਨ ਕਤਾਰ (${count})`,
      `ஆஃப்லைன் வரிசை (${count})`,
      `ఆఫ్‌లైన్ క్యూ (${count})`,
      `ഓഫ്‌ലൈൻ ക്യൂ (${count})`
    );
    return map[targetLang];
  }

  // 3. Mask protected medicine names and brand tokens before applying phrase/word rules
  const maskedTokens: string[] = [];
  let working = rawText;
  for (const pat of PROTECTED_MEDICINE_PATTERNS) {
    working = working.replace(pat, (match) => {
      const idx = maskedTokens.length;
      maskedTokens.push(match);
      return `__MEDRESQ_PROTECTED_${idx}__`;
    });
  }

  // 4. Apply multi-word sub-phrase replacements
  for (const rule of SUB_PHRASE_RULES) {
    if (working.includes(rule.en)) {
      working = working.split(rule.en).join(rule.t[targetLang]);
    }
  }

  // 5. Apply whole-word domain vocabulary replacements
  for (const vocab of WORD_VOCABULARY) {
    working = working.replace(vocab.regex, vocab.t[targetLang]);
  }

  // 6. Restore protected tokens
  working = working.replace(/__MEDRESQ_PROTECTED_(\d+)__/g, (_m, idxStr) => {
    const idx = Number(idxStr);
    return maskedTokens[idx] ?? '';
  });

  return working;
}
